package Core_Programming.Control_Flows.L01;


import java.util.Scanner;
public class D02_L01_18{
    public static void main(String[] args){
        Scanner sc=new Scanner(System.in);
        int n=sc.nextInt();
        for(int i=6;i<=9;i++)
            System.out.println(n+" * "+i+" = "+(n*i));
    }
}
